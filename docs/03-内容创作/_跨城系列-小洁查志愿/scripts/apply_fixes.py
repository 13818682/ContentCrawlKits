    txt = open(path, encoding='utf-8').read()
    for old, new in pairs:
        n = txt.count(old)
        if n == 0:
            errors.append(f'{key}: NOT FOUND -> {old[:50]}')
        elif n > 1:
            errors.append(f'{key}: MULTIPLE({n}) -> {old[:50]}')
        else:
            txt = txt.replace(old, new, 1)
    open(path, 'w', encoding='utf-8', newline='').write(txt)

