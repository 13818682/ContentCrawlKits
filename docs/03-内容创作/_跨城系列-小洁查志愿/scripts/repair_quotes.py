"""对 8 篇改稿 md 的引号做全局重配对：
所有引号字符（" 与 弯引号）按出现顺序交替分配为 “ ”（左开右关），
修复 fix2 全局交替造成的反转错位。html 已确认正确，跳过。"""
import os

ROOT = r'E:\1.HSEE\6.ContentCrawlKits\docs\03-内容创作\_跨城系列-小洁查志愿'
def P(d, f):
    return os.path.join(ROOT, d, '01.公众号', f)

FILES = {
    '01': P('第01篇-一个妈妈的深夜提问', '第01篇-一个妈妈的深夜提问-公众号-优化意见与改稿.md'),
    '02': P('第02篇-家长最常卡住的五个地方', '第02篇-家长最常卡住的五个地方-公众号-优化意见与改稿.md'),
    '03': P('第03篇-这个念头我放了很多年', '第03篇-这个念头我放了很多年-公众号-优化意见与改稿.md'),
    '04': P('第04篇-说干就干我们是怎么开始的', '第04篇-说干就干我们是怎么开始的-公众号-优化意见与改稿.md'),
    '05': P('第05篇-四座城市我们一座一座来', '第05篇-四座城市我们一座一座来-公众号-优化意见与改稿.md'),
    '06': P('第06篇-为什么我们不直接抄网上的分数线', '第06篇-为什么我们不直接抄网上的分数线-公众号-优化意见与改稿.md'),
    '07': P('第07篇-初二家长现在做这三件事', '第07篇-初二家长现在做这三件事-公众号-优化意见与改稿.md'),
    '08': P('第08篇-四座城市都齐了', '第08篇-四座城市都齐了-公众号-优化意见与改稿.md'),
}

for k, p in FILES.items():
    txt = open(p, encoding='utf-8').read()
    out = []
    q = 0
    for ch in txt:
        if ch in '"\u201c\u201d':
            q += 1
            out.append('\u201c' if q % 2 == 1 else '\u201d')
        else:
            out.append(ch)
    if q % 2 == 1:
        print(f'{k}: WARN 奇数引号 {q}，未写入')
        continue
    open(p, 'w', encoding='utf-8', newline='').write(''.join(out))
    print(f'{k}: 重配对 {q} 个引号（{q//2} 对）')
print('done')
