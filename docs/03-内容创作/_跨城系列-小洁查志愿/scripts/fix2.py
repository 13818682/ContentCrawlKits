LQ, RQ = '\u201c', '\u201d'

def convert_md(txt):
    q = 0
    out = []
    for ch in txt:
        if ch == '"':
            q += 1
            out.append(LQ if q % 2 == 1 else RQ)
        else:
            out.append(ch)
    if q % 2 == 1:
        raise RuntimeError(f'奇数个直引号: {q}')
    return ''.join(out), q

def convert_html(txt):
    # 保护 <style> 块
    blocks = re.findall(r'<style.*?</style>', txt, re.S)
    masked = re.sub(r'<style.*?</style>', '\x00', txt, flags=re.S)
    out = []
    in_tag = False
    q = 0
    for ch in masked:
        if ch == '<':
            in_tag = True
            out.append(ch)
        elif ch == '>':
            in_tag = False
            out.append(ch)
        elif ch == '"' and not in_tag:
            q += 1
            out.append(LQ if q % 2 == 1 else RQ)
        else:
            out.append(ch)
    if q % 2 == 1:
        raise RuntimeError(f'HTML 正文奇数个直引号: {q}')
    result = ''.join(out)
    for i, b in enumerate(blocks):
        result = result.replace('\x00', b, 1)
    return result, q

